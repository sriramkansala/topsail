import AppKit
import Combine
import UniformTypeIdentifiers

/// One thing that was copied, kept exactly as the pasteboard held it so it can be put back.
struct ClipboardItem: Identifiable {
    enum Content {
        case text(String)
        case link(URL)
        /// A small copy for the list, and the picture's size in pixels.
        case image(thumbnail: NSImage, pixels: CGSize)
        case files([URL])
    }

    var id = UUID()
    let content: Content
    let copiedAt: Date
    /// Every type of every pasteboard item, with its data, as copied.
    fileprivate let representations: [[NSPasteboard.PasteboardType: Data]]
    /// Equal for the same text, link, files or picture, so copying one again moves it to the top.
    fileprivate let fingerprint: Int
    /// The size of `representations`, for the history's memory budget.
    fileprivate let byteCount: Int
}

/// What you copy, newest first, while Topsail runs. Kept in memory only: nothing is written to
/// disk or sent anywhere, and the history is gone when Topsail quits — except items the user pins,
/// which are saved in Topsail's Application Support folder and kept until unpinned. Items that
/// password managers mark as concealed or transient are never kept.
///
/// macOS has no notification for copies, so the pasteboard's change count is checked twice a
/// second; that count is all it takes to show "Copied to clipboard". Reading what was copied needs
/// the user's permission (Privacy & Security › Paste from Other Apps), so the history waits for
/// "Always Allow" rather than asking on every copy.
@MainActor
final class ClipboardHistory: ObservableObject {
    /// Whether Topsail may read what other apps copy.
    enum Access: Equatable {
        /// Never asked: reading once makes macOS ask, and lists Topsail in System Settings.
        case notDetermined
        /// macOS asks each time, or refuses: the history needs "Always Allow".
        case needsAlwaysAllow
        case allowed
    }

    static let limit = 50

    /// Recent copies, newest first.
    @Published private(set) var items: [ClipboardItem] = []
    /// Kept forever (on disk), most recently pinned first; never cleared or pushed out.
    @Published private(set) var pinned: [ClipboardItem] = []
    @Published private(set) var access: Access
    /// Something was copied (by another app; Topsail's own copies don't count).
    var onCopy: (() -> Void)?
    /// Off: copies are still noticed (for "Copied to clipboard") but nothing is read or kept.
    var keepsHistory = true {
        didSet { if !keepsHistory { items = [] } }
    }

    private let pasteboard = NSPasteboard.general
    private var changeCount: Int
    private var timer: Timer?
    private var ticks = 0

    /// Types that password managers and the like add to say "don't keep this"
    /// (nspasteboard.org's conventions, plus a few apps' own).
    private static let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "com.typeit4me.clipping",
        "de.petermaurer.TransientPasteboardType",
        "Pasteboard generator type",
        "net.antelle.keeweb",
    ]
    /// Larger copies are announced but not kept. A full-screen screenshot fits.
    private static let maxItemBytes = 100 * 1024 * 1024
    /// All items together; the oldest go first to stay under it.
    private static let maxTotalBytes = 200 * 1024 * 1024
    private static let imageTypes: [NSPasteboard.PasteboardType] = [
        .png, NSPasteboard.PasteboardType(UTType.jpeg.identifier),
        NSPasteboard.PasteboardType(UTType.heic.identifier), .tiff,
    ]

    init() {
        changeCount = pasteboard.changeCount
        access = Self.currentAccess()
        loadPinned()
    }

    func start() {
        guard timer == nil else { return }
        changeCount = pasteboard.changeCount
        refreshAccess()
        let timer = Timer(timeInterval: 0.5, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.tick() }
        }
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    /// Stops watching and forgets the recent copies (pinned ones stay).
    func stop() {
        timer?.invalidate()
        timer = nil
        items = []
    }

    func clear() {
        items = []
    }

    /// Puts an item back on the clipboard, as it was copied. A recent one moves to the top; a
    /// pinned one stays where it is.
    func copy(_ item: ClipboardItem) {
        let restored: [NSPasteboardItem] = item.representations.map { types in
            let pasteboardItem = NSPasteboardItem()
            for (type, data) in types {
                pasteboardItem.setData(data, forType: type)
            }
            return pasteboardItem
        }
        pasteboard.clearContents()
        pasteboard.writeObjects(restored)
        // Topsail's own copy: not a new item, no "Copied" popup.
        changeCount = pasteboard.changeCount
        guard !pinned.contains(where: { $0.id == item.id }) else { return }
        items.removeAll { $0.id == item.id }
        items.insert(item, at: 0)
    }

    /// Keeps an item forever: it moves to the pinned list and is saved to disk.
    func pin(_ item: ClipboardItem) {
        guard !pinned.contains(where: { $0.id == item.id }) else { return }
        items.removeAll { $0.id == item.id }
        pinned.insert(item, at: 0)
        save(item)
    }

    /// Back to the recent copies (at the top), and off the disk.
    func unpin(_ item: ClipboardItem) {
        guard pinned.contains(where: { $0.id == item.id }) else { return }
        pinned.removeAll { $0.id == item.id }
        items.insert(item, at: 0)
        if let file = Self.file(for: item.id) { try? FileManager.default.removeItem(at: file) }
    }

    func isPinned(_ item: ClipboardItem) -> Bool {
        pinned.contains { $0.id == item.id }
    }

    func refreshAccess() {
        let current = Self.currentAccess()
        if current != access { access = current }
    }

    /// Opens Privacy & Security › Paste from Other Apps, where "Always Allow" lives. macOS only
    /// lists apps that have asked, so a first read makes it ask (and list Topsail) first.
    func requestAccess() {
        if access == .notDetermined {
            _ = pasteboard.string(forType: .string)
            refreshAccess()
            if access == .allowed {
                capture()
                return
            }
        }
        if let url = URL(string: "x-apple.systempreferences:com.apple.preference.security?Privacy_Pasteboard") {
            NSWorkspace.shared.open(url)
        }
    }

    private static func currentAccess() -> Access {
        switch NSPasteboard.general.accessBehavior {
        case .alwaysAllow: return .allowed
        case .default: return .notDetermined
        default: return .needsAlwaysAllow
        }
    }

    private func tick() {
        ticks += 1
        // While waiting for "Always Allow", notice it within a couple of seconds.
        if access != .allowed, ticks % 4 == 0 { refreshAccess() }

        let count = pasteboard.changeCount
        guard count != changeCount else { return }
        changeCount = count
        onCopy?()
        refreshAccess()
        // Reading would make macOS ask on every copy until "Always Allow" is chosen.
        if access == .allowed, keepsHistory { capture() }
    }

    /// Reads what is on the clipboard now and keeps it, unless it is marked secret, too large, or
    /// of a kind the list can't show.
    private func capture() {
        guard let pasteboardItems = pasteboard.pasteboardItems, !pasteboardItems.isEmpty else { return }
        let types = Set(pasteboardItems.flatMap(\.types).map(\.rawValue))
        guard types.isDisjoint(with: Self.ignoredTypes) else { return }

        var representations: [[NSPasteboard.PasteboardType: Data]] = []
        var bytes = 0
        for pasteboardItem in pasteboardItems {
            var dictionary: [NSPasteboard.PasteboardType: Data] = [:]
            // Dynamic types are another app's private conversions, and a picture's TIFF is the
            // same picture again, far larger, when a PNG comes with it.
            let hasPNG = pasteboardItem.types.contains(.png)
            for type in pasteboardItem.types where !type.rawValue.hasPrefix("dyn.") && !(hasPNG && type == .tiff) {
                guard let data = pasteboardItem.data(forType: type) else { continue }
                bytes += data.count
                guard bytes <= Self.maxItemBytes else { return }
                dictionary[type] = data
            }
            if !dictionary.isEmpty { representations.append(dictionary) }
        }
        guard let (content, fingerprint) = describe(representations) else { return }
        // Already pinned: it stays there, not twice in the list.
        guard !pinned.contains(where: { $0.fingerprint == fingerprint }) else { return }

        let item = ClipboardItem(content: content, copiedAt: Date(), representations: representations,
                                 fingerprint: fingerprint, byteCount: bytes)
        items.removeAll { $0.fingerprint == fingerprint }
        items.insert(item, at: 0)
        if items.count > Self.limit { items.removeLast(items.count - Self.limit) }
        while items.count > 1, items.reduce(0, { $0 + $1.byteCount }) > Self.maxTotalBytes {
            items.removeLast()
        }
    }

    /// What the list shows for a copy: files, a picture, a link or text, in that order of
    /// preference (a copied file also carries its name as text; a picture from a browser, its
    /// address).
    private func describe(_ representations: [[NSPasteboard.PasteboardType: Data]]) -> (ClipboardItem.Content, Int)? {
        guard let first = representations.first else { return nil }

        let fileURLs = representations.compactMap { item -> URL? in
            guard let data = item[.fileURL], let string = String(data: data, encoding: .utf8) else { return nil }
            return URL(string: string)
        }
        if !fileURLs.isEmpty {
            return (.files(fileURLs), fileURLs.map(\.absoluteString).hashValue)
        }

        if let data = Self.imageTypes.lazy.compactMap({ first[$0] }).first, let image = NSImage(data: data) {
            let rep = image.representations.first
            let pixels = CGSize(width: rep?.pixelsWide ?? Int(image.size.width),
                                height: rep?.pixelsHigh ?? Int(image.size.height))
            return (.image(thumbnail: Self.thumbnail(of: image), pixels: pixels), data.hashValue)
        }

        guard let data = first[.string], let string = String(data: data, encoding: .utf8) else { return nil }
        let trimmed = string.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !trimmed.isEmpty else { return nil }
        if !trimmed.contains(where: \.isWhitespace), let url = URL(string: trimmed),
           let scheme = url.scheme?.lowercased(), scheme == "http" || scheme == "https", url.host != nil {
            return (.link(url), string.hashValue)
        }
        return (.text(string), string.hashValue)
    }

    // MARK: Pinned items on disk

    /// One pinned item as saved: everything needed to put it back on the clipboard. What the list
    /// shows is worked out again on loading.
    private struct StoredItem: Codable {
        let id: UUID
        let copiedAt: Date
        let pinnedAt: Date
        let representations: [[String: Data]]
    }

    /// Application Support/Topsail/Pinned (inside the App Store build's container).
    private static var folder: URL? {
        FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask).first?
            .appendingPathComponent("Topsail/Pinned", isDirectory: true)
    }

    private static func file(for id: UUID) -> URL? {
        folder?.appendingPathComponent("\(id.uuidString).plist")
    }

    private func save(_ item: ClipboardItem) {
        guard let folder = Self.folder, let file = Self.file(for: item.id) else { return }
        let stored = StoredItem(id: item.id, copiedAt: item.copiedAt, pinnedAt: Date(),
                                representations: item.representations.map { types in
                                    Dictionary(uniqueKeysWithValues: types.map { ($0.key.rawValue, $0.value) })
                                })
        let encoder = PropertyListEncoder()
        encoder.outputFormat = .binary
        do {
            try FileManager.default.createDirectory(at: folder, withIntermediateDirectories: true)
            try encoder.encode(stored).write(to: file, options: .atomic)
        } catch {
            NSLog("Topsail: could not save a pinned clipboard item: \(error.localizedDescription)")
        }
    }

    private func loadPinned() {
        guard let folder = Self.folder,
              let files = try? FileManager.default.contentsOfDirectory(at: folder, includingPropertiesForKeys: nil)
        else { return }
        let decoder = PropertyListDecoder()
        let stored = files.filter { $0.pathExtension == "plist" }
            .compactMap { try? decoder.decode(StoredItem.self, from: Data(contentsOf: $0)) }
            .sorted { $0.pinnedAt > $1.pinnedAt }
        pinned = stored.compactMap { stored in
            let representations = stored.representations.map { types in
                Dictionary(uniqueKeysWithValues: types.map { (NSPasteboard.PasteboardType($0.key), $0.value) })
            }
            guard let (content, fingerprint) = describe(representations) else { return nil }
            return ClipboardItem(id: stored.id, content: content, copiedAt: stored.copiedAt,
                                 representations: representations, fingerprint: fingerprint,
                                 byteCount: representations.reduce(0) { $0 + $1.values.reduce(0) { $0 + $1.count } })
        }
    }

    /// A copy small enough to keep 50 of and draw in a list row: at most 128 pixels a side,
    /// drawn at 2x.
    private static func thumbnail(of image: NSImage) -> NSImage {
        let maxPixels: CGFloat = 128
        let scale = min(1, maxPixels / max(image.size.width, image.size.height, 1))
        let pixelsWide = max(1, Int((image.size.width * scale).rounded()))
        let pixelsHigh = max(1, Int((image.size.height * scale).rounded()))
        guard let bitmap = NSBitmapImageRep(bitmapDataPlanes: nil, pixelsWide: pixelsWide, pixelsHigh: pixelsHigh,
                                            bitsPerSample: 8, samplesPerPixel: 4, hasAlpha: true, isPlanar: false,
                                            colorSpaceName: .deviceRGB, bytesPerRow: 0, bitsPerPixel: 0) else {
            return image
        }
        NSGraphicsContext.saveGraphicsState()
        NSGraphicsContext.current = NSGraphicsContext(bitmapImageRep: bitmap)
        NSGraphicsContext.current?.imageInterpolation = .high
        image.draw(in: CGRect(x: 0, y: 0, width: pixelsWide, height: pixelsHigh), from: .zero, operation: .copy, fraction: 1)
        NSGraphicsContext.restoreGraphicsState()
        bitmap.size = CGSize(width: CGFloat(pixelsWide) / 2, height: CGFloat(pixelsHigh) / 2)
        let thumbnail = NSImage(size: bitmap.size)
        thumbnail.addRepresentation(bitmap)
        return thumbnail
    }
}
